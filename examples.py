"""Examples based on the class notes: Python operators."""
# Arithmetic operators
x, y = 10, 5
print("Addition:", x + y)
print("Subtraction:", x - y)
print("Multiplication:", x * y)
print("Division:", x / y)
print("Floor division:", 7 // 2)
print("Modulus:", 7 % 2)
print("Exponentiation:", 7 ** 2)

# Comparison and logical operators
print("10 == 10:", 10 == 10)
print("10 != 20:", 10 != 20)
print("Both conditions:", 10 > 5 and 20 > 10)

# Assignment operators
score = 40
score += 10
print("Updated score:", score)

# Membership operators
course = "PYTHON PROGRAM"
print("PYTHON" in course)
